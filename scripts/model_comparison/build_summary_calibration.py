"""Summary calibration page for a restricted set of forecast-weather models.

Writes ``calibration.html`` with the binned plots:
- coverage of the 90% interval by predicted-load bin;
- conditional reliability curves at the common 5/50/95% quantiles.

Only quantile models are included; point-only models are skipped. No model is
re-run.

    python scripts/model_comparison/build_summary_calibration.py
"""

import argparse
import datetime
import subprocess
import sys
from pathlib import Path

from build_calibration_report import check_horizons, fig_by_level, fig_interval
from compare_predictions import read_predictions
from model_registry import model_colour

from electricity_load_forecasting import diagnostics as dg
from electricity_load_forecasting.metrics import PINBALL_LEVELS

MODELS = {
    "hgb_quantile_q7": "HGB quantile",
    "hgb_quantile_recal_q7": "HGB quantile recalibrated",
    "tabicl_n8_full": "TabICL",
    "tabicl_recal_n8_full": "TabICL recalibrated",
    "tabicl_forecast_ctx1024_n4": "TabICL forecast",
    "kumo_tabular": "Kumo-Tabular",
    "chronos2_ctx4000": "Chronos-2",
    "t0_gamma": "t0-gamma",
}
DEFAULT_MODELS = list(MODELS)


def load_models(directory, wanted):
    models = []
    for name in wanted:
        path = directory / f"{name}_cv_predictions.parquet"
        if not path.exists():
            raise SystemExit(f"missing {path}")
        df = read_predictions(path)
        if not dg.pred_columns(df):
            print(f"skipping {name}: no quantile predictions")
            continue
        models.append((MODELS.get(name, name), df, model_colour(name)))
    if not models:
        raise SystemExit("no quantile models to plot")
    return models


def provenance(args, models):
    try:
        commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
        dirty = subprocess.check_output(
            ["git", "status", "--porcelain"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        commit, dirty = "unknown", ""
    command = " ".join(sys.argv)
    return f"""# Summary calibration page

Generated by `scripts/model_comparison/build_summary_calibration.py`.

- command: `python {command}` (run from the repository root)
- date: {datetime.datetime.now().isoformat(timespec="seconds")}
- git commit: `{commit}` ({"clean" if not dirty else "dirty (see git status)"})
- input directory: `{args.dir.resolve()}`
- weather: safe-lead forecast (this directory), oracle not used
- models: {", ".join(name for name, _, _ in models)}
- excluded: point-only models (no quantiles)
- interval: {min(PINBALL_LEVELS)}-{max(PINBALL_LEVELS)}
- reliability levels: {", ".join(str(q) for q in PINBALL_LEVELS)}
- bins: {args.n_bins} equal-count bins by predicted median
- no model was re-run; derived from `*_cv_predictions.parquet`
"""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dir",
        type=Path,
        default=Path("results/model_comparison/cv_comparison_forecast"),
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=Path("results/model_comparison/summary"),
    )
    parser.add_argument(
        "--models",
        default=",".join(DEFAULT_MODELS),
        help="comma-separated model names (default: the summary quantile models)",
    )
    parser.add_argument("--n_bins", type=int, default=10)
    parser.add_argument("--figure_height", type=int, default=620)
    parser.add_argument("--page_width", type=int, default=1600)
    args = parser.parse_args()

    wanted = [name.strip() for name in args.models.split(",") if name.strip()]
    models = load_models(args.dir, wanted)
    horizons = check_horizons(models)

    interval = fig_interval(models, horizons, args.n_bins)
    interval.update_layout(height=args.figure_height)
    binned = fig_by_level(
        models, horizons, args.n_bins, method="bins", levels=PINBALL_LEVELS
    )
    binned.update_layout(height=args.figure_height)

    interval_html = interval.to_html(
        full_html=False,
        include_plotlyjs=True,
        config={"responsive": True, "displaylogo": False},
    )
    binned_html = binned.to_html(
        full_html=False,
        include_plotlyjs=False,
        config={"responsive": True, "displaylogo": False},
    )
    names = ", ".join(name for name, _, _ in models)
    page = f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>Calibration summary: binned coverage and reliability</title>
<style>
body {{ font-family: sans-serif; max-width: {args.page_width}px; margin: 2em auto; padding: 0 1em; }}
.chart {{ width: 100%; margin-bottom: 1.2em; }}
.note {{ color: #555; font-size: 0.9em; }}
</style>
</head>
<body>
<h1>Calibration summary: binned coverage and reliability</h1>
<p class="note">Safe-lead forecast weather. Models: {names}. Point-only models
(HGB mean, HGB mean fast, KumoForecast) have no quantiles and are omitted.
The interval is the central {min(PINBALL_LEVELS)}&ndash;{max(PINBALL_LEVELS)}
range; reliability is shown only at the common
{", ".join(str(q) for q in PINBALL_LEVELS)} quantile levels so models with
different quantile sets remain comparable. Cases are split into {args.n_bins}
equal-count bins by each model's predicted median.</p>
<h2>Binned coverage of the 90% interval</h2>
<p class="note">Observed coverage of the 5&ndash;95% interval in each
predicted-median bin. Below the dashed nominal line means the interval is too
narrow at that load level; above means too wide.</p>
<div class="chart">{interval_html}</div>
<h2>Binned conditional reliability (5/50/95)</h2>
<p class="note">Equal-count bins of each model's own predictions; x is the mean
prediction and y is the estimated conditional quantile from the residuals in
the bin. A perfectly calibrated model lies on the dashed 45&deg; diagonal. Use
the dropdown to change the horizon.</p>
<div class="chart">{binned_html}</div>
</body>
</html>
"""
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "calibration.html").write_text(page, "utf-8")
    (args.output_dir / "calibration.md").write_text(provenance(args, models), "utf-8")
    print(f"wrote {args.output_dir / 'calibration.html'}")


if __name__ == "__main__":
    main()
